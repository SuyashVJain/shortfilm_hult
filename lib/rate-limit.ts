import "server-only";

/**
 * Tiny in-memory sliding-window limiter. Per server instance only, which is
 * enough to blunt abuse at this event's scale (architecture §9, E2).
 */
const hits = new Map<string, number[]>();

export function rateLimit(key: string, limit: number, windowMs: number) {
  const now = Date.now();
  const recent = (hits.get(key) ?? []).filter((t) => now - t < windowMs);
  if (recent.length >= limit) {
    hits.set(key, recent);
    return false;
  }
  recent.push(now);
  hits.set(key, recent);
  return true;
}
